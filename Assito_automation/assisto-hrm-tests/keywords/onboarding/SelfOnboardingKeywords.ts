import { Page, expect } from '@playwright/test';
import {
  SelfOnboardingPage,
  type SelfOnboardingStep,
} from '@pages/onboarding/SelfOnboardingPage';
import { SetPasswordPage } from '@pages/onboarding/SetPasswordPage';
import { LoginKeywords } from '@keywords/LoginKeywords';
import { getBaseUrl, getLoginUrl } from '@utils/helpers';
import { generateAlphaName } from '@utils/testDataGenerator';

/** Values the employee supplies on the Personal Profile step. */
export interface PersonalProfileData {
  fathersName: string;
  mothersName: string;
  placeOfBirth?: string;
  nationality?: string;
  religion?: string;
  residentialStatus?: string;
  maritalStatus: string;
  addressLine1: string;
  addressLine2?: string;
  city: string;
  pinCode: string;
  /** Emergency contact — every field here is required by the app. */
  emergencyContactPerson: string;
  emergencyDialCode: string;
  emergencyContactNumber: string;
  emergencyRelationship: string;
}

/** Payroll bank details for the Statutory step. Test data only. */
export interface StatutoryData {
  accountHolderName: string;
  bankName: string;
  accountNumber: string;
  ifscCode: string;
  branch?: string;
}

/**
 * SelfOnboardingKeywords drives the employee-facing Self-Onboarding wizard,
 * from the "Joining Confirmed" email through to Complete Onboarding.
 *
 * Synchronisation is on application state throughout — visible/enabled
 * assertions and step-indicator polling — rather than fixed waits.
 */
export class SelfOnboardingKeywords {
  private readonly page: Page;
  private readonly selfPage: SelfOnboardingPage;
  private readonly passwordPage: SetPasswordPage;
  private readonly loginKeywords: LoginKeywords;

  constructor(page: Page) {
    this.page = page;
    this.selfPage = new SelfOnboardingPage(page);
    this.passwordPage = new SetPasswordPage(page);
    this.loginKeywords = new LoginKeywords(page);
  }

  // ==========================================
  //  PASSWORD SETUP + FIRST LOGIN
  // ==========================================

  /** Open the password-setup link extracted from the joining email. */
  async openPasswordSetupLink(link: string): Promise<void> {
    expect(
      link,
      'No password setup link was supplied — the joining email was not parsed',
    ).toContain('http');
    await this.page.goto(link, { waitUntil: 'domcontentloaded' });
  }

  /**
   * Verify the Set Password page rendered and that it is setting a password
   * for the EXPECTED employee — never just "a password page appeared".
   */
  async verifySetPasswordPage(expectedEmail: string): Promise<void> {
    await expect(
      this.passwordPage.heading,
      `Set-password page did not render for ${expectedEmail} ` +
        `(current URL: ${this.page.url()})`,
    ).toBeVisible({ timeout: 30000 });

    // The page sets a password for the ORGANISATION mail, while the link
    // arrived at the personal mail — so this logs what the app shows and only
    // asserts an address is present, rather than demanding a match that is
    // wrong by design.
    const shownFor = await this.passwordPage.getSettingPasswordForEmail();
    console.log(`[SelfOnboarding] Set-password page is for: ${shownFor}`);
    expect(
      shownFor,
      `Set-password page showed no account address (expected the org mail for ${expectedEmail})`,
    ).not.toBe('');
  }

  /**
   * Set the employee's password.
   *
   * @param password Generated by the caller (utils/helpers.randomPassword) so
   *   no credential is hardcoded; the app requires 8-16 characters with an
   *   uppercase, a lowercase, a number and a special character.
   */
  async setPassword(password: string): Promise<void> {
    await expect(this.passwordPage.newPasswordInput).toBeEditable();
    await this.passwordPage.fillNewPassword(password);
    await this.passwordPage.fillConfirmPassword(password);
    await expect(this.passwordPage.setPasswordButton).toBeEnabled();
    await this.passwordPage.clickSetPassword();
    console.log('[SelfOnboarding] Password set for the new joiner');
  }

  /** The set-password form disappearing is the app confirming it took. */
  async verifyPasswordSetSucceeded(): Promise<void> {
    await expect(
      this.passwordPage.setPasswordButton,
      'Password setup did not complete — the form stayed on screen',
    ).toBeHidden({ timeout: 30000 });
  }

  /**
   * Log in as the employee. Handles the Privacy Policy consent dialog the app
   * shows on a first login; it is skipped silently when already accepted.
   */
  async loginAsEmployee(email: string, password: string): Promise<void> {
    await this.loginKeywords.openLoginPage(getLoginUrl());

    const emailField = this.page.locator('#login-email, input[type="email"]').first();
    await expect(emailField).toBeEditable({ timeout: 30000 });
    await emailField.fill(email);

    const passwordField = this.page.locator('#login-password, input[type="password"]').first();
    await expect(
      passwordField,
      `Login password field never became editable (URL: ${this.page.url()})`,
    ).toBeEditable({ timeout: 30000 });
    await passwordField.fill(password);

    const submitBtn = this.page.getByRole('button', { name: /sign in|login/i }).first();
    await submitBtn.click();
    console.log(`[SelfOnboarding] Submitted login form for: ${email}`);

    // Check for Privacy Policy modal
    const modal = this.page.locator('[role="dialog"]').first();
    try {
      if (await modal.isVisible({ timeout: 6000 })) {
        console.log('[SelfOnboarding] Privacy Policy modal appeared — accepting');
        const cb = modal.locator('input[type="checkbox"]').first();
        await cb.check({ force: true }).catch(() => {});
        const continueBtn = modal.getByRole('button', { name: 'Continue' });
        await continueBtn.click();
        await modal.waitFor({ state: 'hidden', timeout: 15000 }).catch(() => {});
      }
    } catch {
      // Modal didn't appear or already accepted
    }

    // Wait for URL to leave login
    await this.page.waitForURL((url) => !url.pathname.includes('login'), { timeout: 20000 });
    await this.page.waitForLoadState('networkidle').catch(() => {});
    console.log(`[SelfOnboarding] Employee logged in! Current URL: ${this.page.url()}`);
  }

  async acceptPrivacyPolicyIfShown(): Promise<void> {
    if (await this.passwordPage.isPrivacyPolicyShown()) {
      console.log('[SelfOnboarding] Accepting the Privacy Policy consent dialog');
      await this.passwordPage.acceptPrivacyPolicy();
      await expect(this.passwordPage.privacyPolicyDialog.first()).toBeHidden({
        timeout: 20000,
      }).catch(() => {});
    }
  }

  // ==========================================
  //  WIZARD
  // ==========================================

  async navigateToSelfOnboarding(): Promise<void> {
    await this.page.goto(`${getBaseUrl()}/people/onboarding/self-onboarding`, {
      waitUntil: 'domcontentloaded',
    });
    await this.page.waitForLoadState('networkidle').catch(() => {});
  }

  async verifyWelcomePage(expectedEmployeeId?: string): Promise<void> {
    await expect(
      this.selfPage.welcomeHeading,
      `Self-Onboarding Welcome page did not render (URL: ${this.page.url()})`,
    ).toBeVisible({ timeout: 30000 });

    if (expectedEmployeeId) {
      await expect(
        this.page.getByText(expectedEmployeeId, { exact: false }),
        `Welcome page is not showing employee ID ${expectedEmployeeId} — ` +
          'this may be a different employee',
      ).toBeVisible({ timeout: 15000 });
    }
  }

  /**
   * The step the wizard is currently on, 1-8 (0 when the indicator is absent).
   *
   * Self-Onboarding is resumable: once a step is saved the employee re-enters
   * the wizard at their current position, not at Welcome. Callers use this to
   * skip work the employee has already completed instead of asserting on a
   * screen that will never render again.
   */
  async getCurrentStep(): Promise<number> {
    return await this.selfPage.getCurrentStepNumber();
  }

  async isOnboardingSubmitted(): Promise<boolean> {
    await Promise.race([
      this.selfPage.submittedForApprovalBanner.waitFor({ state: 'visible', timeout: 15000 }).catch(() => {}),
      this.selfPage.stepIndicator.waitFor({ state: 'visible', timeout: 15000 }).catch(() => {}),
      this.selfPage.welcomeHeading.waitFor({ state: 'visible', timeout: 15000 }).catch(() => {}),
    ]);

    const isSubmitted = await this.selfPage.submittedForApprovalBanner
      .isVisible()
      .catch(() => false);
    if (isSubmitted) return true;

    return await this.page
      .getByText(/(read-only until HR finishes|is with HR|journey is complete)/i)
      .isVisible()
      .catch(() => false);
  }

  async beginOnboarding(): Promise<void> {
    await expect(this.selfPage.beginOnboardingButton).toBeVisible();
    await expect(this.selfPage.beginOnboardingButton).toBeEnabled();
    await this.selfPage.clickBeginOnboarding();
  }

  /** Assert the wizard advanced to a given step, by name and number. */
  async verifyOnStep(
    step: SelfOnboardingStep,
    expectedNumber: number,
  ): Promise<void> {
    try {
      await expect
        .poll(async () => await this.selfPage.getCurrentStepNumber(), {
          timeout: 30000,
        })
        .toBe(expectedNumber);
    } catch {
      // Staying put almost always means the app rejected the save. Surface its
      // OWN validation messages — otherwise this reads as "step 2, expected 3"
      // with no indication of which field is at fault.
      const problems = await this.collectValidationMessages();
      const actual = await this.selfPage.getCurrentStepNumber();
      throw new Error(
        `Expected to reach step ${expectedNumber} ("${step}") but the wizard ` +
          `is still on step ${actual} (URL: ${this.page.url()}).` +
          (problems.length
            ? `\nThe page is reporting:\n  - ${problems.join('\n  - ')}`
            : '\nThe page reported no validation message.'),
      );
    }
  }

  /** Visible validation/error text on the current step, de-duplicated. */
  private async collectValidationMessages(): Promise<string[]> {
    const texts = await this.page
      .locator('[role="alert"], [class*="error" i], [aria-invalid="true"]')
      .filter({ visible: true })
      .allTextContents()
      .catch(() => [] as string[]);

    const required = await this.page
      .getByText(/is required|please (enter|select|fill)|mandatory/i)
      .allTextContents()
      .catch(() => [] as string[]);

    return [...new Set([...texts, ...required].map(t => t.trim()).filter(Boolean))]
      .slice(0, 12);
  }

  // ----- Step 2: Personal Profile -----

  async completePersonalProfile(data: PersonalProfileData): Promise<void> {
    await expect(this.selfPage.personalDetailsHeading).toBeVisible({
      timeout: 20000,
    });

    // Only the genuinely-required fields are filled. Address, personal email
    // and date of birth arrive PRE-FILLED from Pre-Onboarding (confirmed
    // against the live form), so overwriting them would fight the app and risk
    // changing data the candidate already submitted.
    await this.selfPage.fathersNameInput.fill(data.fathersName);
    await this.selfPage.mothersNameInput.fill(data.mothersName);

    if (data.placeOfBirth) {
      await this.selfPage.placeOfBirthInput.fill(data.placeOfBirth);
    }
    if (data.nationality) {
      await this.selfPage.nationalityInput.fill(data.nationality);
    }
    if (data.religion) {
      await this.selfPage.religionInput.fill(data.religion);
    }
    if (data.residentialStatus) {
      await this.selfPage.residentialStatusInput.fill(data.residentialStatus);
    }

    // Marital Status is a combobox with fixed options (Single / Married /
    // Divorced / Widowed) whose list renders in a portal. Unlike the modal
    // dropdowns this one sits on a full page, so clicking the option is safe.
    await this.selfPage.maritalStatusDropdown.click();
    await this.page
      .getByRole('option', { name: data.maritalStatus, exact: true })
      .click();

    await this.selfPage.differentlyAbledNoRadio.check();

    // Address comes across from Pre-Onboarding; only fill gaps.
    await this.fillIfEmpty(this.selfPage.addressLine1Input, data.addressLine1);
    await this.fillIfEmpty(this.selfPage.addressPinCodeInput, data.pinCode);

    // Emergency contact is required — the app rejects Save & continue with
    // "Emergency contact person / Dial code / Contact number / Relationship
    // is required" until all four are supplied.
    await this.selfPage.emergencyContactPersonInput.fill(data.emergencyContactPerson);
    await this.selfPage.emergencyContactNumberInput.fill(data.emergencyContactNumber);
    await this.selfPage.emergencyRelationshipInput.fill(data.emergencyRelationship);

    // Dial code is a searchable combobox; typing and pressing Enter commits
    // the match, the pattern this app needs throughout.
    await this.selfPage.emergencyDialCodeInput.click();
    await this.selfPage.emergencyDialCodeInput.fill(data.emergencyDialCode);
    await this.page.waitForTimeout(600);
    await this.page.keyboard.press('Enter');
    await this.page.waitForTimeout(300);
    // Log what actually committed: picking the wrong country silently
    // changes the phone-length rule (a mismatch shows up later as an
    // unexplained "Must be N digits").
    console.log(
      `[SelfOnboarding] Emergency dial code committed as ` +
        `"${await this.selfPage.emergencyDialCodeInput.inputValue().catch(() => '')}"`,
    );

    console.log('[SelfOnboarding] Personal Profile completed');
    await this.selfPage.clickContinue();
  }

  /** Fill a field only when it is empty, so pre-filled data is preserved. */
  private async fillIfEmpty(
    locator: import('@playwright/test').Locator,
    value: string,
  ): Promise<void> {
    const current = await locator.inputValue().catch(() => '');
    if (current.trim()) return;
    await locator.fill(value);
  }

  // ----- Step 3: Identity Details -----

  /**
   * Complete Identity Details, honouring the pre-onboarding rule: documents
   * already submitted during Pre-Onboarding must NOT be uploaded again.
   *
   * The decision is taken from the app's own "N of M submitted" counter and
   * each document's row state, never assumed. Only genuinely missing documents
   * are uploaded.
   *
   * @returns names of the documents this step actually uploaded.
   */
  async completeIdentityDetails(documentNames: readonly string[]): Promise<string[]> {
    await expect(this.selfPage.identityHeading).toBeVisible({ timeout: 20000 });

    const counts = await this.selfPage.getDocumentSubmissionCounts();
    console.log(
      `[SelfOnboarding] Identity documents: ${counts.submitted} of ` +
        `${counts.required} already submitted`,
    );

    const uploaded: string[] = [];

    if (counts.required > 0 && counts.submitted >= counts.required) {
      console.log(
        '[SelfOnboarding] All identity documents already exist from ' +
          'Pre-Onboarding — skipping upload, as required',
      );
    } else {
      for (const documentName of documentNames) {
        if (await this.selfPage.isDocumentSubmitted(documentName)) {
          console.log(
            `[SelfOnboarding] "${documentName}" already submitted — not re-uploading`,
          );
          continue;
        }
        console.log(
          `[SelfOnboarding] "${documentName}" is missing — uploading`,
        );
        await this.selfPage.uploadDocument(
          documentName,
          generateAlphaName(6),
          'test-data/test-upload.png',
        );
        // Checked against the app's own COUNTER, not the row text: once a
        // document flips to submitted its row markup changes, and reading the
        // row reported failure for an upload that had in fact gone through.
        await expect
          .poll(
            async () =>
              (await this.selfPage.getDocumentSubmissionCounts()).submitted,
            {
              timeout: 30000,
              message:
                `The submitted-document count did not rise after uploading ` +
                `"${documentName}"`,
            },
          )
          .toBeGreaterThan(uploaded.length);

        uploaded.push(documentName);
      }
    }

    await this.selfPage.acknowledgeDocumentReceipt();
    await this.selfPage.clickContinue();

    return uploaded;
  }

  // ----- Step 4: Employment And Education -----

  /**
   * Employment details are read-only (populated from Temporary Registration),
   * so this verifies them against the identity carried through the workflow
   * rather than typing over them.
   */
  async completeEmploymentAndEducation(expected: {
    employeeId?: string;
    workEmail?: string;
  }): Promise<void> {
    await expect(this.selfPage.employmentHeading).toBeVisible({
      timeout: 20000,
    });

    if (expected.employeeId) {
      await expect(
        this.selfPage.employeeIdField,
        'Employment step shows a different Employee ID — wrong employee',
      ).toHaveValue(expected.employeeId);
    }
    if (expected.workEmail) {
      await expect(
        this.selfPage.workEmailField,
        'Employment step shows a different work email — wrong employee',
      ).toHaveValue(new RegExp(expected.workEmail, 'i'));
    }

    // "Save & continue" is disabled while this step's tables are empty, so an
    // Educational Documents record is added when — and only when — the app is
    // blocking. A step that is already satisfied is left untouched.
    const advanceReady = await this.selfPage.isAdvanceEnabled();
    if (!advanceReady) {
      console.log(
        '[SelfOnboarding] Employment step is blocking — adding an education record',
      );
      await this.selfPage.addEducationRecord(
        generateAlphaName(8),
        'test-data/test-upload.png',
      );
    }

    await this.selfPage.clickContinue();
  }

  // ----- Step 5: Statutory -----

  async completeStatutory(data: StatutoryData): Promise<void> {
    await expect(this.selfPage.statutoryHeading).toBeVisible({ timeout: 20000 });

    const accountHolderInput = this.page
      .locator('div')
      .filter({ hasText: /^Account Holder Name/i })
      .locator('input')
      .first();

    const bankNameInput = this.page
      .locator('div')
      .filter({ hasText: /^Bank Name/i })
      .locator('input')
      .first();

    const accountNumberInput = this.page
      .locator('div')
      .filter({ hasText: /^Account Number/i })
      .locator('input')
      .first();

    const ifscCodeInput = this.page
      .locator('div')
      .filter({ hasText: /^IFSC Code/i })
      .locator('input')
      .first();

    const branchInput = this.page
      .locator('div')
      .filter({ hasText: /^Branch/i })
      .locator('input')
      .first();

    if (await accountHolderInput.isVisible({ timeout: 5000 }).catch(() => false)) {
      await accountHolderInput.scrollIntoViewIfNeeded().catch(() => {});
      await accountHolderInput.fill(data.accountHolderName);
      await bankNameInput.fill(data.bankName);
      await accountNumberInput.fill(data.accountNumber);
      await ifscCodeInput.fill(data.ifscCode);
      if (data.branch && (await branchInput.isVisible().catch(() => false))) {
        await branchInput.fill(data.branch);
      }
      console.log('[SelfOnboarding] Statutory payroll details completed');
    } else {
      const bankInputs = this.page.locator('input[type="text"], input:not([type])');
      const count = await bankInputs.count();
      if (count >= 4) {
        await bankInputs.nth(0).fill(data.accountHolderName);
        await bankInputs.nth(1).fill(data.bankName);
        await bankInputs.nth(2).fill(data.accountNumber);
        await bankInputs.nth(3).fill(data.ifscCode);
        if (data.branch && count >= 5) {
          await bankInputs.nth(4).fill(data.branch);
        }
        console.log('[SelfOnboarding] Statutory payroll details completed via fallback inputs');
      } else {
        console.log(
          '[SelfOnboarding] No bank account inputs on Statutory step — advancing with defaults',
        );
      }
    }

    await this.selfPage.clickContinue();
  }

  // ----- Step 6: Agreements And Policies -----

  async completeAgreementsAndPolicies(documents: {
    agreements: readonly string[];
    policies: readonly string[];
  }): Promise<void> {
    await expect(this.selfPage.agreementsHeading).toBeVisible({
      timeout: 20000,
    });

    const current = await this.selfPage.getAgreementsCompletion();
    const requiredTotal = documents.agreements.length + documents.policies.length;
    if (current.done >= requiredTotal || (current.total > 0 && current.done >= current.total)) {
      console.log(
        `[SelfOnboarding] All agreements and policies already completed (${current.done}/${current.total || requiredTotal}) — skipping to Continue`,
      );
      await this.selfPage.clickContinue();
      return;
    }

    for (const policy of documents.policies) {
      await this.selfPage.clickAcknowledgePolicy(policy);
      console.log(`[SelfOnboarding] Policy acknowledged: ${policy}`);
    }

    for (const agreement of documents.agreements) {
      await this.selfPage.clickSignAgreement(agreement);
      console.log(`[SelfOnboarding] Agreement signed: ${agreement}`);
      // TODO(assisto): the Sign action opens a signature component whose
      // markup is not yet confirmed; the completion counter below is what
      // proves whether signing actually registered.
    }

    await expect
      .poll(async () => (await this.selfPage.getAgreementsCompletion()).done, {
        timeout: 30000,
        message:
          'Agreements/policies never reached full completion — Continue will ' +
          'stay disabled',
      })
      .toBeGreaterThanOrEqual(current.total > 0 ? current.total : requiredTotal);

    await this.selfPage.clickContinue();
  }

  // ----- Steps 7-8: Induction / Meet The Team -----

  async completeInduction(): Promise<void> {
    await expect(this.selfPage.inductionHeading).toBeVisible({ timeout: 20000 });
    await this.selfPage.clickContinue();
  }

  async completeMeetTheTeam(): Promise<void> {
    await expect(this.selfPage.meetTheTeamHeading).toBeVisible({
      timeout: 20000,
    });
  }

  async completeOnboarding(): Promise<void> {
    const isSubmitted = await this.isOnboardingSubmitted();
    if (isSubmitted) {
      console.log('[SelfOnboarding] Already submitted — skipping complete click');
      return;
    }
    await expect(this.selfPage.completeOnboardingButton.first()).toBeVisible({
      timeout: 20000,
    });
    await expect(this.selfPage.completeOnboardingButton.first()).toBeEnabled();
    await this.selfPage.clickCompleteOnboarding();
  }

  async verifyOnboardingCompleted(): Promise<void> {
    await expect(
      this.selfPage.submittedForApprovalBanner.or(
        this.page.getByText(/(read-only until HR finishes|is with HR|journey is complete|submitted|under review)/i),
      ),
      `Onboarding completion was not confirmed (URL: ${this.page.url()})`,
    ).toBeVisible({ timeout: 30000 });
    console.log('[SelfOnboarding] Employee onboarding submitted for HR approval');
  }
}
